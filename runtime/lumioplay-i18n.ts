export const lumioplayStrings: Record<LumioplayLang, Record<LumioplayStringKey, string>> = { en, sv }

export type LumioplayTranslate = (key: LumioplayStringKey) => string

export function translate(lang: LumioplayLang, key: LumioplayStringKey): string {
  return lumioplayStrings[lang]?.[key] ?? en[key]
}

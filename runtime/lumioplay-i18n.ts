// Lumioplay ships its own string catalog: the plugin bundle resolves
// `@/lib/plugin-sdk` to the local runtime-host shim, so the host app's i18n
// module is never reachable from here. The active language still comes from
// the host (see `useLang` in the shim) so the plugin follows the app's
// language picker.
//
// Interpolation follows the host convention: keys carry `{placeholder}`
// tokens and the call site does `.replace('{placeholder}', value)`.

